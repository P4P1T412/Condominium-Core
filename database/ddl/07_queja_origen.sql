DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
  FROM USER_TAB_COLUMNS
  WHERE TABLE_NAME = 'QUEJA' AND COLUMN_NAME = 'ORIGEN';

  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[ALTER TABLE QUEJA ADD (origen VARCHAR2(20) DEFAULT 'PORTAL' NOT NULL)]';
  END IF;

  SELECT COUNT(*) INTO v_count
  FROM USER_CONSTRAINTS
  WHERE TABLE_NAME = 'QUEJA' AND CONSTRAINT_NAME = 'CK_QUEJA_ORIGEN';

  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[ALTER TABLE QUEJA ADD CONSTRAINT ck_queja_origen CHECK (origen IN ('PORTAL', 'PRESENCIAL', 'TELEFONO', 'CORREO', 'WHATSAPP', 'OTRO'))]';
  END IF;
END;
/
