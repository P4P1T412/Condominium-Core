DECLARE
  v_count NUMBER;
  v_nullable VARCHAR2(1);
BEGIN
  SELECT COUNT(*) INTO v_count
  FROM USER_TAB_COLUMNS
  WHERE TABLE_NAME = 'QUEJA' AND COLUMN_NAME = 'ID_USUARIO_REGISTRA';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE QUEJA ADD (id_usuario_registra NUMBER)';
  END IF;

  EXECUTE IMMEDIATE 'UPDATE QUEJA SET id_usuario_registra = id_usuario WHERE id_usuario_registra IS NULL';

  SELECT nullable INTO v_nullable
  FROM USER_TAB_COLUMNS
  WHERE TABLE_NAME = 'QUEJA' AND COLUMN_NAME = 'ID_USUARIO';
  IF v_nullable = 'N' THEN
    EXECUTE IMMEDIATE 'ALTER TABLE QUEJA MODIFY (id_usuario NULL)';
  END IF;

  SELECT nullable INTO v_nullable
  FROM USER_TAB_COLUMNS
  WHERE TABLE_NAME = 'QUEJA' AND COLUMN_NAME = 'ID_USUARIO_REGISTRA';
  IF v_nullable = 'Y' THEN
    EXECUTE IMMEDIATE 'ALTER TABLE QUEJA MODIFY (id_usuario_registra NOT NULL)';
  END IF;

  SELECT COUNT(*) INTO v_count
  FROM USER_CONSTRAINTS
  WHERE TABLE_NAME = 'QUEJA' AND CONSTRAINT_NAME = 'FK_QUEJA_USUARIO_REGISTRA';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE QUEJA ADD CONSTRAINT fk_queja_usuario_registra FOREIGN KEY (id_usuario_registra) REFERENCES USUARIO (id_usuario)';
  END IF;
END;
